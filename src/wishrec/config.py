@dataclass(frozen=True)
class Source:
    """A pinned HuggingFace dataset file."""

    name: str
    repo: str
    revision: str
    filename: str
    sha256: str
    expected_rows: int
    licence: str

    @property
    def url(self) -> str:
        return (
            f"https://huggingface.co/datasets/{self.repo}/resolve/{self.revision}/{self.filename}"
        )


