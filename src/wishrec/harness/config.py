"""Paths, constants and endpoint configuration for the R1 ReAct harness.

The generator is an OpenAI-compatible vLLM endpoint serving ``Qwen/Qwen3-8B-AWQ`` by
default.  Nothing in this module reads a paid API: the endpoint, key and timeout are
operator-provided environment variables, and the shipped example uses a local vLLM
server.  The frozen embedding encoder and the detector live in :mod:`wishrec.detector`.
"""

