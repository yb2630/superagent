def utc_now_iso() -> str:
    """Return the current UTC time as an ISO-8601 string with whole seconds."""
    return datetime.now(UTC).replace(microsecond=0).isoformat()


def sha256_text(text: str) -> str:
    """Return the hex SHA-256 of ``text`` encoded as UTF-8."""
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def sha256_file(path: Path) -> str:
    """Return the hex SHA-256 of a file, read in 1 MiB chunks."""
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def git_info() -> dict:
    """Return the repository commit, branch and dirty flag (``unknown`` outside git)."""

    def _git(*args: str) -> str:
        try:
            return subprocess.check_output(
                ["git", *args], cwd=REPO_ROOT, stderr=subprocess.DEVNULL, text=True
            ).strip()
        except (OSError, subprocess.CalledProcessError):
            return ""

    status = _git("status", "--porcelain")
    return {
        "commit": _git("rev-parse", "HEAD") or "unknown",
        "branch": _git("rev-parse", "--abbrev-ref", "HEAD") or "unknown",
        "dirty": bool(status),
    }


def environment_info() -> dict:
    """Return the Python version and platform details recorded in run manifests."""
    return {
        "python": sys.version.split()[0],
        "platform": platform.platform(),
        "machine": platform.machine(),
        "processor": platform.processor(),
    }


def atomic_write_text(path: Path, text: str) -> None:
    """Write ``text`` via a ``.part`` file and rename, so readers never see a partial file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".part")
    temporary.write_text(text, encoding="utf-8")
    temporary.replace(path)


def atomic_write_json(path: Path, data: dict) -> None:
    """Atomically write ``data`` as indented, key-sorted JSON."""
    atomic_write_text(path, json.dumps(data, indent=2, sort_keys=True, ensure_ascii=False) + "\n")


def write_jsonl(path: Path, records: list[dict]) -> None:
    """Atomically write one key-sorted JSON object per line."""
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [json.dumps(record, sort_keys=True, ensure_ascii=False) for record in records]
    atomic_write_text(path, "\n".join(lines) + ("\n" if lines else ""))


def read_jsonl(path: Path) -> list[dict]:
    """Read a JSON-lines file, skipping blank lines."""
    return [
        json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()
    ]


@dataclass(frozen=True)
class EndpointConfig:
    """One OpenAI-compatible chat-completions endpoint."""

    base_url: str = DEFAULT_BASE_URL
    api_key: str = DEFAULT_API_KEY
    model: str = DEFAULT_MODEL
    timeout: float = DEFAULT_TIMEOUT
    max_retries: int = DEFAULT_MAX_RETRIES
    tool_mode: str = "auto"
    temperature: float = GENERATOR_TEMPERATURE
    top_p: float = GENERATOR_TOP_P
    # Qwen3 thinks unless told not to, so the generator sends an explicit False.  None
    # omits vLLM's chat_template_kwargs entirely (for non-vLLM endpoints).
    enable_thinking: bool | None = False
    extra_headers: dict[str, str] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if self.tool_mode not in TOOL_MODES:
            raise ValueError(f"tool_mode must be one of {TOOL_MODES}, got {self.tool_mode!r}")
        if not self.base_url.strip():
            raise ValueError("base_url must not be empty")
        if not self.model.strip():
            raise ValueError("model must not be empty")

    @property
    def safe_identity(self) -> dict:
        """Endpoint identity for manifests; never includes the API key."""
        return {
            "base_url": self.base_url,
            "model": self.model,
            "tool_mode": self.tool_mode,
            "temperature": self.temperature,
            "top_p": self.top_p,
            "enable_thinking": self.enable_thinking,
        }

    @classmethod
    def from_env(
        cls,
        *,
        prefix: str = "VLLM",
        environ: Mapping[str, str] | None = None,
        fallback: EndpointConfig | None = None,
    ) -> EndpointConfig:
        """Read an endpoint from ``<PREFIX>_*`` variables.

        ``prefix="VLLM"`` reads ``VLLM_BASE_URL``, ``VLLM_API_KEY``, ``VLLM_MODEL``,
        ``VLLM_TIMEOUT``, ``VLLM_MAX_RETRIES``, ``VLLM_TOOL_MODE``, ``VLLM_TEMPERATURE``,
        ``VLLM_TOP_P``, ``VLLM_ENABLE_THINKING`` and ``VLLM_EXTRA_HEADERS`` (JSON object).
        Missing values fall back to the generator defaults, or to ``fallback`` when given
        (used by B3 to reuse the generator endpoint unless a frontier endpoint is set).
        """
        env = os.environ if environ is None else environ
        base = fallback
        default = cls() if base is None else base
        raw_headers = env.get(f"{prefix}_EXTRA_HEADERS", "").strip()
        headers = dict(default.extra_headers)
        if raw_headers:
            parsed = json.loads(raw_headers)
            if not isinstance(parsed, dict):
                raise ValueError(f"{prefix}_EXTRA_HEADERS must be a JSON object")
            headers = {str(key): str(value) for key, value in parsed.items()}
        return cls(
            base_url=env.get(f"{prefix}_BASE_URL", default.base_url).strip(),
            api_key=env.get(f"{prefix}_API_KEY", default.api_key).strip(),
            model=env.get(f"{prefix}_MODEL", default.model).strip(),
            timeout=float(env.get(f"{prefix}_TIMEOUT", default.timeout)),
            max_retries=int(env.get(f"{prefix}_MAX_RETRIES", default.max_retries)),
            tool_mode=env.get(f"{prefix}_TOOL_MODE", default.tool_mode).strip().lower(),
            temperature=float(env.get(f"{prefix}_TEMPERATURE", default.temperature)),
            top_p=float(env.get(f"{prefix}_TOP_P", default.top_p)),
            enable_thinking=_optional_truthy(
                env.get(f"{prefix}_ENABLE_THINKING"), default.enable_thinking
            ),
            extra_headers=headers,
        )


def _truthy(value: str) -> bool:
    return str(value).strip().lower() in {"1", "true", "yes", "on"}


def _optional_truthy(value: str | None, default: bool | None) -> bool | None:
    """Parse an optional boolean variable, keeping ``default`` when it is unset."""
    return default if value is None else _truthy(value)


def generator_config(environ: Mapping[str, str] | None = None) -> EndpointConfig:
    """Return the generator endpoint configured by the ``VLLM_*`` variables."""
    return EndpointConfig.from_env(prefix="VLLM", environ=environ)


def frontier_config(environ: Mapping[str, str] | None = None) -> EndpointConfig:
    """Return the B3 endpoint configured by ``VLLM_FRONTIER_*``, else the generator's.

    The milestone uses a frontier baseline when the operator supplies one.  With the $0
    budget and no other endpoint, B3 reuses the same Qwen3-8B endpoint at temperature 0.7,
    as the R1 ticket specifies; the model identity is recorded in the run manifest.  A
    frontier endpoint on a different host inherits only non-secret settings: its key and
    headers come from ``VLLM_FRONTIER_API_KEY`` / ``VLLM_FRONTIER_EXTRA_HEADERS``.
    """
    env = os.environ if environ is None else environ
    generator = generator_config(env)
    fallback = generator
    frontier_url = env.get("VLLM_FRONTIER_BASE_URL", "").strip()
    if frontier_url and frontier_url != generator.base_url:
        # A different host must not receive the generator's key or tunnel headers, nor
        # vLLM's chat_template_kwargs extension; it needs its own VLLM_FRONTIER_* values.
        fallback = replace(
            generator, api_key=DEFAULT_API_KEY, extra_headers={}, enable_thinking=None
        )
    return EndpointConfig.from_env(prefix="VLLM_FRONTIER", environ=env, fallback=fallback)


def harness_source_hash() -> str:
    """Hash the harness and detector sources so a run records the exact code it used."""
    digest = hashlib.sha256()
    for directory in (
        Path(__file__).resolve().parent,
        Path(__file__).resolve().parents[1] / "detector",
    ):
        if not directory.exists():
            continue
        for path in sorted(directory.glob("*.py")):
            digest.update(str(path.relative_to(REPO_ROOT)).encode("utf-8"))
            digest.update(path.read_bytes())
    return digest.hexdigest()


